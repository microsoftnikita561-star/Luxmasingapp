// relab_logic.h — portable key-validation logic for all 5 challenges.
// NO Windows dependencies: compiles on Linux too, so the exact same algorithms
// are unit-tested natively (see tools/logic_test.c) to guarantee the published
// keys / keygens are correct. The Windows challenges wrap these with GUI +
// anti-debug + anti-tamper layers.
#pragma once
#include <cstdint>
#include <cstddef>
#include <string>
#include <cstring>
#include <cctype>

namespace relab {

// =====================================================================
// LEVEL 1 — "QuickReels"  (trivial: plaintext comparison)
// The whole key sits in the binary as a readable string.
// =====================================================================
inline const char* L1_KEY(){ return "QR-2024-PRO-ACCESS"; }
inline bool l1_check(const std::string& in){ return in == L1_KEY(); }

// =====================================================================
// LEVEL 2 — "PhotoGlow Pro"  (XOR-encoded key + patchable branch)
// The key is stored XOR'd with 0x5A so no plaintext is visible; it is
// decoded into a local buffer and compared. Alternatively the single
// conditional jump can be patched.
// =====================================================================
inline unsigned char L2_XOR(){ return 0x5A; }
// Encoded bytes (plaintext XOR 0x5A). Generated by tools/gen (printed, then pasted).
static const unsigned char L2_ENC[] = {
    0x1d,0x16,0x15,0x0d,0x77,0x0a,0x08,0x15,0x77,0x6d,0x1c,0x69,0x1b,0x77,0x63,0x19,0x68,0x1e
};
inline std::string l2_decoded(){
    std::string s; s.reserve(sizeof(L2_ENC));
    for(size_t i=0;i<sizeof(L2_ENC);++i) s.push_back((char)(L2_ENC[i]^L2_XOR()));
    return s;
}
inline bool l2_check(const std::string& in){
    std::string k = l2_decoded();
    if(in.size()!=k.size()) return false;        // the branch IDA shows
    for(size_t i=0;i<k.size();++i) if(in[i]!=k[i]) return false;
    return true;
}

// =====================================================================
// LEVEL 3 — "VaultDrive"  (keygenme: serial derived from the name)
// No magic string to find: you must reverse the algorithm into a keygen.
// =====================================================================
inline uint32_t djb2(const std::string& s){
    uint32_t h = 5381;
    for(unsigned char c : s) h = h*33u + c;
    return h;
}
inline std::string l3_serial(const std::string& name){
    uint32_t h = djb2(name);
    uint32_t magic = h ^ 0x5A17C0DEu;
    uint32_t a = (magic >> 16) & 0xFFFF;
    uint32_t b =  magic        & 0xFFFF;
    uint32_t c = (h*0x1Fu + (uint32_t)name.size()*7u) & 0xFFFF;
    char buf[32];
    std::snprintf(buf,sizeof(buf),"%04X-%04X-%04X", a,b,c);
    return std::string(buf);
}
inline std::string upper(std::string s){ for(char&c:s) c=(char)std::toupper((unsigned char)c); return s; }
inline bool l3_check(const std::string& name, const std::string& serial){
    if(name.empty()) return false;
    return upper(serial) == l3_serial(name);
}

// =====================================================================
// LEVEL 4 — "SentinelVPN"  (anti-debug gated serial)
// The constant mixed into the serial differs when a debugger is present,
// so a correct serial is rejected under a debugger until anti-debug is
// bypassed. Strings are also stored encrypted (see challenge .cpp).
// =====================================================================
inline uint32_t crc32(const std::string& s){
    uint32_t c = 0xFFFFFFFFu;
    for(unsigned char ch : s){
        c ^= ch;
        for(int k=0;k<8;++k) c = (c>>1) ^ (0xEDB88320u & (uint32_t)(-(int)(c&1)));
    }
    return c ^ 0xFFFFFFFFu;
}
inline uint32_t L4_K_REAL(){ return 0x1337C0DEu; } // no debugger
inline uint32_t L4_K_FAKE(){ return 0xDEADBEEFu; } // debugger detected -> wrong
inline std::string l4_serial(const std::string& name, uint32_t k){
    uint32_t crc = crc32(name);
    uint32_t mixed = crc ^ k;
    mixed = (mixed<<7) | (mixed>>25);
    uint32_t a = (mixed>>20)&0xFFF;
    uint32_t b = (mixed>>8)&0xFFF;
    uint32_t c =  mixed&0xFF;
    char buf[32];
    std::snprintf(buf,sizeof(buf),"VPN-%03X-%03X-%02X", a,b,c);
    return std::string(buf);
}
inline bool l4_check(const std::string& name, const std::string& serial, bool debuggerPresent){
    if(name.empty()) return false;
    uint32_t k = debuggerPresent ? L4_K_FAKE() : L4_K_REAL();
    return upper(serial) == l4_serial(name, k);
}

// =====================================================================
// LEVEL 5 — "PhantomCheat"  (bytecode VM + anti-tamper + anti-debug)
// The key check is not a direct compare: a tiny stack/accumulator VM
// interprets a byte program that transforms the key, then the result is
// compared to an embedded target blob. The transform is invertible, so a
// keygen can recover the exact key from the target (see tools/gen).
// An integrity checksum over the VM program folds into the seed, so naive
// patching of the program corrupts the output.
// =====================================================================
enum L5Op { OP_LDK=1, OP_ADDT, OP_XORT, OP_ROLT, OP_ADDP, OP_STP, OP_HLT };
static const unsigned char L5_PROG[] = {
    OP_LDK, OP_ADDT, OP_XORT, OP_ROLT, OP_ADDP, OP_STP, OP_HLT
};
static const unsigned char L5_KSTREAM[8] = {0x2A,0x9E,0x13,0x7C,0xF1,0x55,0xC3,0x88};
inline int  L5_N(){ return 22; }
inline unsigned char L5_SEED(){ return 0x6D; }

inline unsigned char rol8(unsigned char v,int r){ r&=7; return (unsigned char)((v<<r)|(v>>(8-r))); }
inline unsigned char ror8(unsigned char v,int r){ r&=7; return (unsigned char)((v>>r)|(v<<(8-r))); }

inline unsigned char l5_addtab(int i){ return (unsigned char)((0x3B + i*7) & 0xFF); }
inline unsigned char l5_xortab(int i){ return L5_KSTREAM[i&7]; }
inline int           l5_roltab(int i){ return (i%7)+1; }

// Integrity checksum over the VM program (anti-tamper). If the program bytes
// are patched, this changes and the seed below shifts -> wrong output.
inline unsigned char l5_integrity(){
    unsigned char s = 0xA5;
    for(size_t i=0;i<sizeof(L5_PROG);++i) s = (unsigned char)((s + L5_PROG[i]*3) ^ (s>>3));
    return s;
}
// Expected integrity value baked in at generation time. When the program is
// untampered, (runtime ^ expected) == 0 and the VM seed is exactly L5_SEED().
inline unsigned char L5_INTEGRITY_EXPECTED(){ return 0x11; }

// The interpreter. acc/prev are the VM registers; it runs L5_PROG once per byte.
inline void l5_vm(const unsigned char* key, int n, unsigned char* out){
    unsigned char prev = (unsigned char)(L5_SEED() ^ (l5_integrity() ^ L5_INTEGRITY_EXPECTED()));
    for(int i=0;i<n;++i){
        unsigned char acc = 0;
        for(size_t pc=0; pc<sizeof(L5_PROG); ++pc){
            switch(L5_PROG[pc]){
                case OP_LDK:  acc = key[i]; break;
                case OP_ADDT: acc = (unsigned char)(acc + l5_addtab(i)); break;
                case OP_XORT: acc = (unsigned char)(acc ^ l5_xortab(i)); break;
                case OP_ROLT: acc = rol8(acc, l5_roltab(i)); break;
                case OP_ADDP: acc = (unsigned char)(acc + prev); break;
                case OP_STP:  out[i] = acc; prev = acc; break;
                case OP_HLT:  pc = sizeof(L5_PROG); break;
            }
        }
    }
}

// Inverse of the VM transform (the keygen). Recovers key from out[].
inline void l5_invert(const unsigned char* out, int n, unsigned char* key){
    unsigned char prev = (unsigned char)(L5_SEED()); // untampered seed
    for(int i=0;i<n;++i){
        unsigned char y = out[i];
        unsigned char t = (unsigned char)(y - prev);
        t = ror8(t, l5_roltab(i));
        t = (unsigned char)(t ^ l5_xortab(i));
        t = (unsigned char)(t - l5_addtab(i));
        key[i] = t;
        prev = y;
    }
}

// Target blob = l5_vm("PH4NTOM-VM-2024-UNLOCK"). Generated by tools/gen.
static const unsigned char L5_TARGET[22] = {
    0xb0,0x00,0x73,0xa1,0xec,0x2a,0xe2,0x04,0x93,0x5d,0x38,0x10,0xa3,0x71,0x95,0xfa,0x4b,0x34,
    0xf6,0xd2,0xcf,0x67
};
inline bool l5_check(const std::string& key){
    if((int)key.size()!=L5_N()) return false;
    unsigned char out[64];
    l5_vm((const unsigned char*)key.data(), L5_N(), out);
    return std::memcmp(out, L5_TARGET, L5_N())==0;
}

} // namespace relab
